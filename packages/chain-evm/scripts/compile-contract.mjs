// Compiles contracts/ConkernftzCollection.sol with solc-js, resolving OpenZeppelin
// imports from node_modules, and emits src/artifact.ts (ABI + bytecode). The artifact is
// committed so the package build never requires solc. Re-run with `pnpm compile-contract`
// whenever the contract changes.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const solc = require('solc');
const here = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.resolve(here, '..');
const ozRoot = path.dirname(require.resolve('@openzeppelin/contracts/package.json'));

const contractPath = path.join(pkgRoot, 'contracts', 'ConkernftzCollection.sol');
const source = fs.readFileSync(contractPath, 'utf8');

function findImports(importPath) {
  try {
    if (importPath.startsWith('@openzeppelin/contracts/')) {
      const rel = importPath.slice('@openzeppelin/contracts/'.length);
      return { contents: fs.readFileSync(path.join(ozRoot, rel), 'utf8') };
    }
    return { error: 'Unsupported import: ' + importPath };
  } catch (e) {
    return { error: 'File not found: ' + importPath + ' (' + e.message + ')' };
  }
}

const input = {
  language: 'Solidity',
  sources: { 'ConkernftzCollection.sol': { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
const errors = (output.errors || []).filter((e) => e.severity === 'error');
if (errors.length > 0) {
  console.error(errors.map((e) => e.formattedMessage).join('\n'));
  process.exit(1);
}

const contract = output.contracts['ConkernftzCollection.sol']['ConkernftzCollection'];
const abi = contract.abi;
const bytecode = '0x' + contract.evm.bytecode.object;

const out = `// AUTO-GENERATED by scripts/compile-contract.mjs — do not edit by hand.
// Source: contracts/ConkernftzCollection.sol (OpenZeppelin ERC-721 + ERC-2981).
/* eslint-disable */
export const conkernftzCollectionAbi = ${JSON.stringify(abi, null, 2)} as const;

export const conkernftzCollectionBytecode = ${JSON.stringify(bytecode)} as \`0x\${string}\`;
`;
fs.writeFileSync(path.join(pkgRoot, 'src', 'artifact.ts'), out);
console.log(`Wrote src/artifact.ts (${abi.length} ABI entries, ${bytecode.length} bytecode chars)`);
