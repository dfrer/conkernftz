// Compiles the project's Solidity contracts with solc-js, resolving OpenZeppelin and ERC721A
// imports from node_modules, and emits committed TS artifacts (ABI + bytecode) so the package
// build never requires solc. Re-run with `pnpm compile-contract` whenever a contract changes.
//
//   contracts/ConkernftzCollection.sol -> src/artifact.ts        (simple owner-mint collection)
//   contracts/ConkernftzLaunch.sol     -> src/launch-artifact.ts (phased launch mint)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const solc = require('solc');
const here = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.resolve(here, '..');
const ozRoot = path.dirname(require.resolve('@openzeppelin/contracts/package.json'));
const erc721aRoot = path.dirname(require.resolve('erc721a/package.json'));

// Resolve `import` paths solc encounters back to files on disk. Both packages also use relative
// imports internally; solc resolves those against the importing unit's name (e.g. an
// `@openzeppelin/contracts/access/Ownable.sol` importing `../utils/Context.sol` becomes
// `@openzeppelin/contracts/utils/Context.sol`), so prefix-matching covers the whole tree.
function findImports(importPath) {
  try {
    if (importPath.startsWith('@openzeppelin/contracts/')) {
      const rel = importPath.slice('@openzeppelin/contracts/'.length);
      return { contents: fs.readFileSync(path.join(ozRoot, rel), 'utf8') };
    }
    if (importPath.startsWith('erc721a/')) {
      const rel = importPath.slice('erc721a/'.length);
      return { contents: fs.readFileSync(path.join(erc721aRoot, rel), 'utf8') };
    }
    return { error: 'Unsupported import: ' + importPath };
  } catch (e) {
    return { error: 'File not found: ' + importPath + ' (' + e.message + ')' };
  }
}

// Each entry: the .sol source file, the contract name within it, and the artifact to emit.
const TARGETS = [
  {
    file: 'ConkernftzCollection.sol',
    contract: 'ConkernftzCollection',
    out: 'artifact.ts',
    abiConst: 'conkernftzCollectionAbi',
    bytecodeConst: 'conkernftzCollectionBytecode',
    note: 'OpenZeppelin ERC-721 + ERC-2981',
  },
  {
    file: 'ConkernftzLaunch.sol',
    contract: 'ConkernftzLaunch',
    out: 'launch-artifact.ts',
    abiConst: 'conkernftzLaunchAbi',
    bytecodeConst: 'conkernftzLaunchBytecode',
    note: 'ERC-721A phased launch (allowlist -> public -> reveal)',
  },
];

const sources = {};
for (const t of TARGETS) {
  sources[t.file] = { content: fs.readFileSync(path.join(pkgRoot, 'contracts', t.file), 'utf8') };
}

const input = {
  language: 'Solidity',
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
const errors = (output.errors || []).filter((e) => e.severity === 'error');
if (errors.length > 0) {
  console.error(errors.map((e) => e.formattedMessage).join('\n'));
  process.exit(1);
}
const warnings = (output.errors || []).filter((e) => e.severity === 'warning');
if (warnings.length > 0) {
  console.warn(`(${warnings.length} compiler warning(s))`);
}

for (const t of TARGETS) {
  const contract = output.contracts[t.file][t.contract];
  const abi = contract.abi;
  const bytecode = '0x' + contract.evm.bytecode.object;
  const out = `// AUTO-GENERATED by scripts/compile-contract.mjs — do not edit by hand.
// Source: contracts/${t.file} (${t.note}).
/* eslint-disable */
export const ${t.abiConst} = ${JSON.stringify(abi, null, 2)} as const;

export const ${t.bytecodeConst} = ${JSON.stringify(bytecode)} as \`0x\${string}\`;
`;
  fs.writeFileSync(path.join(pkgRoot, 'src', t.out), out);
  console.log(`Wrote src/${t.out} (${abi.length} ABI entries, ${bytecode.length} bytecode chars)`);
}
